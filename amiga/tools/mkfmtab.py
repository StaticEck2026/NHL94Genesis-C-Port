#!/usr/bin/env python3
"""Write amiga/host/fmtab.h: the tables amiga/host/fmpatch.c renders the game's FM patches with (pure
maths, nothing from the cartridge): a sine over 1,024 steps (Q14), the linear level of an attenuation
in steps of 0.09375 dB (the YM2612's envelope unit, 1,024 steps to 96 dB, Q14), and Paula's volume
(0-64) for an attenuation in 0.75 dB steps (the total level's unit, 0-127).
Usage: mkfmtab.py OUT.h"""
import math
import sys


def main(out):
    sine = [round(16383 * math.sin(2 * math.pi * i / 1024)) for i in range(1024)]
    lin = [round(16384 * 10 ** (-(u * 0.09375) / 20)) for u in range(1024)]
    vol = [round(64 * 10 ** (-(t * 0.75) / 20)) for t in range(128)]

    def rows(name, ctype, vals):
        s = 'static const %s %s[%d] = {\n' % (ctype, name, len(vals))
        for i in range(0, len(vals), 16):
            s += '    ' + ', '.join(str(v) for v in vals[i:i + 16]) + ',\n'
        return s + '};\n'
    with open(out, 'w') as f:
        f.write('/* Generated by amiga/tools/mkfmtab.py: maths only. Do not edit. */\n#pragma once\n#include <stdint.h>\n')
        f.write(rows('fm_sine', 'int16_t', sine))
        f.write(rows('fm_lin', 'uint16_t', lin))
        f.write(rows('fm_vol', 'uint8_t', vol))


if __name__ == '__main__':
    main(sys.argv[1])
